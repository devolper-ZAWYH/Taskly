#!/usr/bin/env node
/**
 * Build Claude's interactive card (server/mcp/cards/view) into one
 * self-contained HTML page, written as a TypeScript module the MCP server
 * serves (server/mcp/cards/card-html.generated.ts, not committed):
 *
 *   yarn cards           build once (dev, build and typecheck run this first)
 *   yarn cards --watch   rebuild on every change while working on the card
 *   yarn cards --check   fail if the generated module is out of date
 */
import { createHash } from "node:crypto"
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import * as esbuild from "esbuild"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const viewDir = join(root, "server/mcp/cards/view")
const outFile = join(root, "server/mcp/cards/card-html.generated.ts")
const args = new Set(process.argv.slice(2))

/**
 * The MCP packages each bring their own copy of zod; one is plenty. This
 * roughly halves the page.
 */
const oneZod = {
  name: "one-zod",
  setup(build) {
    build.onResolve({ filter: /^zod(\/.*)?$/ }, (args) =>
      args.resolveDir === root ? undefined : build.resolve(args.path, { kind: args.kind, resolveDir: root }),
    )
  },
}

const options = {
  entryPoints: [join(viewDir, "main.ts")],
  bundle: true,
  format: "iife",
  target: "es2020",
  minify: true,
  legalComments: "none",
  write: false,
  logLevel: "warning",
  plugins: [oneZod],
}

async function page(script) {
  const css = await esbuild.transform(readFileSync(join(viewDir, "styles.css"), "utf8"), {
    loader: "css",
    minify: true,
  })
  // Inline <script> content must not close the tag early.
  const js = script.replace(/<\/(script)/gi, "<\\/$1")
  if (js.includes("<!--")) throw new Error("The card script contains '<!--', which breaks inline scripts.")
  return (
    '<!doctype html><html lang="en" dir="ltr"><head><meta charset="utf-8">' +
    '<meta name="viewport" content="width=device-width, initial-scale=1">' +
    // Transparent in light and dark mode from the first paint.
    '<meta name="color-scheme" content="light dark">' +
    `<title>Taskly</title><style>${css.code}</style></head>` +
    `<body><div id="root"></div><script>${js}</script></body></html>`
  )
}

function moduleFor(html) {
  const version = createHash("sha256").update(html).digest("hex").slice(0, 12)
  return (
    "// Generated by scripts/build-cards.mjs from server/mcp/cards/view. Don't edit; run `yarn cards`.\n" +
    `export const CARD_VERSION = ${JSON.stringify(version)}\n` +
    `export const CARD_HTML = ${JSON.stringify(html)}\n`
  )
}

async function buildOnce() {
  const result = await esbuild.build(options)
  const html = await page(result.outputFiles[0].text)
  return { source: moduleFor(html), bytes: Buffer.byteLength(html) }
}

if (args.has("--watch")) {
  const context = await esbuild.context({
    ...options,
    plugins: [
      ...options.plugins,
      {
        name: "write-card",
        setup(build) {
          build.onEnd(async (result) => {
            if (result.errors.length > 0) return
            writeFileSync(outFile, moduleFor(await page(result.outputFiles[0].text)))
            console.log(`card rebuilt ${new Date().toLocaleTimeString()}`)
          })
        },
      },
    ],
  })
  await context.watch()
  console.log("Watching server/mcp/cards/view …")
} else {
  const { source, bytes } = await buildOnce()
  if (args.has("--check")) {
    const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : ""
    if (current !== source) {
      console.error("server/mcp/cards/card-html.generated.ts is out of date: run `yarn cards`.")
      process.exit(1)
    }
  } else {
    writeFileSync(outFile, source)
    console.log(`card built (${Math.round(bytes / 1024)} KB)`)
  }
}
